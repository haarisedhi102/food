#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RUST="$ROOT/../../mobile/ios/Rig"
SWIFT="$ROOT/swift"
HEADERS="$SWIFT/artifacts/ios-headers"
OUT="$SWIFT/artifacts/RigPoc.xcframework"

rustup target add --toolchain 1.97.1 aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios

cd "$RUST"
IPHONEOS_DEPLOYMENT_TARGET=17.0 cargo build --release --target aarch64-apple-ios
IPHONEOS_DEPLOYMENT_TARGET=17.0 cargo build --release --target aarch64-apple-ios-sim
IPHONEOS_DEPLOYMENT_TARGET=17.0 cargo build --release --target x86_64-apple-ios

# The UniFFI header + modulemap are generated by scripts/build.sh.
mkdir -p "$HEADERS"
cp "$SWIFT/generated/rig_pocFFI.h" "$HEADERS/"
cp "$SWIFT/generated/rig_pocFFI.modulemap" "$HEADERS/module.modulemap"

SIM_FAT="$SWIFT/artifacts/librig_poc_sim.a"
lipo -create \
  "$RUST/target/aarch64-apple-ios-sim/release/librig_poc.a" \
  "$RUST/target/x86_64-apple-ios/release/librig_poc.a" \
  -output "$SIM_FAT"

rm -rf "$OUT"
xcodebuild -create-xcframework \
  -library "$RUST/target/aarch64-apple-ios/release/librig_poc.a" -headers "$HEADERS" \
  -library "$SIM_FAT" -headers "$HEADERS" \
  -output "$OUT"

echo "created $OUT"
